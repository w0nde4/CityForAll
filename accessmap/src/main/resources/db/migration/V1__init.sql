-- Реальная схема на основе присланной псевдоБД (road, crossing, ramp + 5 справочников).
-- Заменяет черновую схему с обобщённой таблицей points.

CREATE EXTENSION IF NOT EXISTS postgis;

-- ============================================================================
--  Справочники (FK-таблицы). Форма у всех одинаковая: id + variant.
-- ============================================================================

CREATE TABLE curb_height (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant VARCHAR(255) NOT NULL UNIQUE
);
INSERT INTO curb_height (variant) VALUES
    ('<2cm'),
    ('2-4cm'),
    ('4-5cm'),
    ('>5cm');

CREATE TABLE road_surface (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant VARCHAR(255) NOT NULL UNIQUE
);
INSERT INTO road_surface (variant) VALUES
    ('асфальт'),
    ('асфальт плохого качества (с ямами)'),
    ('дорога из брусчатки'),
    ('щебеночное покрытие'),
    ('грунтовка'),
    ('песок'),
    ('плиточное покрытие'),
    ('плохое плиточное покрытие');

CREATE TABLE entrance_type (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant VARCHAR(255) NOT NULL UNIQUE
);
INSERT INTO entrance_type (variant) VALUES
    ('covered'),
    ('open air');

CREATE TABLE crossing_type (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant VARCHAR(255) NOT NULL UNIQUE
);
INSERT INTO crossing_type (variant) VALUES
    ('underground'),
    ('overground');

CREATE TABLE tactile_tile_condition (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant VARCHAR(255) NOT NULL UNIQUE
);
INSERT INTO tactile_tile_condition (variant) VALUES
    ('есть, корректная укладка'),
    ('есть, но частично или некорректно уложенная'),
    ('нет');

-- ============================================================================
--  Объекты на карте (то, что ставит волонтёр). У каждого — своя координата
--  (location) и общие поля created_at/created_by — их нет в исходной
--  псевдоБД, добавлены как общие поля MapObjectEntity (см. комментарий там).
-- ============================================================================

CREATE TABLE road (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location              geometry(Point,4326) NOT NULL,
    created_at            timestamptz          NOT NULL DEFAULT now(),
    created_by            varchar(255),

    traffic_lanes         integer              NOT NULL,
    surface_quality       bigint               NOT NULL REFERENCES road_surface(id),
    tram_tracks           boolean              NOT NULL,
    rail_height           double precision,
    traffic_light         boolean              NOT NULL,
    audible_traffic_light boolean,
    countdown_timer       boolean
);
CREATE INDEX idx_road_location ON road USING GIST (location);

CREATE TABLE crossing (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location               geometry(Point,4326) NOT NULL,
    created_at             timestamptz          NOT NULL DEFAULT now(),
    created_by             varchar(255),

    entrance_type          bigint               NOT NULL REFERENCES entrance_type(id),
    crossing_type          bigint               NOT NULL REFERENCES crossing_type(id),
    ramp                   boolean              NOT NULL,
    lifting_platform       boolean              NOT NULL,
    platform_working       boolean,
    handrails_below_70cm   boolean              NOT NULL,
    stair_contrast_marking boolean              NOT NULL,
    tactile_strip          boolean              NOT NULL,
    lighting               boolean              NOT NULL,
    tactile_tile_condition bigint               NOT NULL REFERENCES tactile_tile_condition(id)
);
CREATE INDEX idx_crossing_location ON crossing USING GIST (location);

CREATE TABLE ramp (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location       geometry(Point,4326) NOT NULL,
    created_at     timestamptz          NOT NULL DEFAULT now(),
    created_by     varchar(255),

    curb_height    bigint               NOT NULL REFERENCES curb_height(id),
    road_access    boolean              NOT NULL,
    walker_barrier boolean              NOT NULL,
    tactile_tile   boolean              NOT NULL,
    ramp_width     double precision,
    angle_slant    double precision
);
CREATE INDEX idx_ramp_location ON ramp USING GIST (location);
